# -*- coding: utf-8 -*-
"""生成订阅文件：live.txt（TVBox 格式）、live.m3u（M3U 格式）、stats.json。"""
import json
import os
from datetime import datetime, timedelta, timezone

CST = timezone(timedelta(hours=8))

# 分组名 → emoji 图标前缀（酷九/tvbox 等播放器直接把 emoji 当分组图标显示）
GROUP_EMOJI_MAP = {
    "央视频道": "📺",
    "卫视频道": "📡",
    "地方频道": "🏙️",
    "4K节目": "🎬",
    "中数传媒": "💠",
    "其他": "📌",
    "IPTV": "🌐",
    "系统": "⚙️",
    "北京节目": "🏯",
    "上海节目": "🌃",
    "广东频道": "🌴",
    "浙江节目": "🌊",
    "江苏节目": "🌸",
    "四川节目": "🐼",
    "重庆节目": "🏔️",
    "山东节目": "⛰️",
    "湖南节目": "🎤",
    "福建节目": "🏝️",
    "港台节目": "🎌",
}


def with_emoji(group_name):
    """给分组名加上 emoji 前缀，找不到则原样返回。"""
    emoji = GROUP_EMOJI_MAP.get(group_name)
    if emoji:
        return f"{emoji} {group_name}"
    return group_name


def now_str():
    return datetime.now(CST).strftime("%Y-%m-%d %H:%M:%S")


def build_txt(entries, up_url=None, updated=None):
    """生成 TVBox 兼容的 TXT：`#分类,#genre#` + `频道名,url`。
    up_url/updated 提供时，末尾追加"系统"分组与"更新时间"条目。"""
    lines = []
    current = None
    for cat, name, url in entries:
        if cat != current:
            lines.append(f"# {with_emoji(cat)},#genre#")
            current = cat
        lines.append(f"{name},{url}")
    if up_url and updated:
        lines.append(f"# {with_emoji('系统')},#genre#")
        lines.append(f"📺 欢迎观看,{up_url}")
    return "\n".join(lines) + "\n"


def build_m3u(entries, logo_map=None, tvgid_map=None, updated=None, epg_url=None, up_url=None, group_logo_map=None):
    """生成 M3U 订阅文件。

    logo_map: {频道名: tvg-logo URL}
    tvgid_map: {频道名: tvg-id}
    group_logo_map: {分组名: group-logo URL}（播放器分组列表显示的小图标）
    epg_url: 节目单（EPG XML）地址，写入头部 #EXT-X-TVG-URL；
             传字符串（单个）或列表（多个，按顺序尝试）
    up_url: 更新时间页面地址；提供时在列表末尾追加"系统"分组条目
    """
    logo_map = logo_map or {}
    tvgid_map = tvgid_map or {}
    group_logo_map = group_logo_map or {}
    lines = []
    head = "#EXTM3U"
    if epg_url:
        urls = epg_url if isinstance(epg_url, (list, tuple)) else [epg_url]
        joined = '","'.join(urls)
        # 同时写 x-tvg-url 与 url-tvg，兼容不同播放器（TiviMate/OTT Navigator 认 url-tvg，
        # 部分播放器认 x-tvg-url）；多源用逗号分隔按序尝试
        head += f' x-tvg-url="{joined}" url-tvg="{joined}"'
    lines.append(head)
    if updated:
        lines.append(f"# Generated by china-iptv-sources, updated at {updated}")
    for cat, name, url in entries:
        attrs = [f'group-title="{with_emoji(cat)}"']
        gl = group_logo_map.get(cat)
        if gl:
            attrs.append(f'group-logo="{gl}"')
        tid = tvgid_map.get(name)
        if tid:
            attrs.insert(0, f'tvg-id="{tid}" tvg-name="{name}"')
        logo = logo_map.get(name)
        if logo:
            attrs.append(f'tvg-logo="{logo}"')
        lines.append(f"#EXTINF:-1 {' '.join(attrs)},{name}")
        lines.append(url)
    # 追加"欢迎观看"系统条目
    if up_url and updated:
        lines.append(f'#EXTINF:-1 group-title="{with_emoji("系统")}",📺 欢迎观看')
        lines.append(up_url)
    return "\n".join(lines) + "\n"


def write_outputs(entries, output_dir, logo_map=None, tvgid_map=None, updated=None, stats=None, epg_url=None, up_url=None, group_logo_map=None):
    """写入 live.txt / live.m3u / uptime.txt / stats.json，返回 (txt, m3u)。"""
    os.makedirs(output_dir, exist_ok=True)
    txt = build_txt(entries, up_url=up_url, updated=updated)
    m3u = build_m3u(entries, logo_map=logo_map, tvgid_map=tvgid_map, updated=updated, epg_url=epg_url, up_url=up_url, group_logo_map=group_logo_map)

    with open(os.path.join(output_dir, "live.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(txt)
    with open(os.path.join(output_dir, "live.m3u"), "w", encoding="utf-8", newline="\n") as f:
        f.write(m3u)
    if stats is not None:
        with open(os.path.join(output_dir, "stats.json"), "w", encoding="utf-8") as f:
            json.dump(stats, f, ensure_ascii=False, indent=2)
    # 更新时间页面（订阅里的"更新时间"条目指向它）
    if up_url and updated:
        lines = [
            "= 订阅更新时间 =",
            f"更新时间：{updated}",
            f"源文件：{stats.get('source', '') if stats else ''}",
            f"解析频道：{stats.get('total', 0) if stats else 0}",
            f"有效频道：{stats.get('valid', 0) if stats else 0}",
            f"失效剔除：{stats.get('dropped', 0) if stats else 0}",
            "",
            "提示：本页面由 NAS 定时任务自动生成，每次推送自动刷新。",
        ]
        with open(os.path.join(output_dir, "uptime.txt"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    return txt, m3u
