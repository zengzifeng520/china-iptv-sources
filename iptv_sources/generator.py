# -*- coding: utf-8 -*-
"""生成订阅文件：live.txt（TVBox 格式）、live.m3u（M3U 格式）、stats.json。"""
import json
import os
from datetime import datetime, timedelta, timezone

CST = timezone(timedelta(hours=8))


def now_str():
    return datetime.now(CST).strftime("%Y-%m-%d %H:%M:%S")


def build_txt(entries):
    """生成 TVBox 兼容的 TXT：`#分类,#genre#` + `频道名,url`。"""
    lines = []
    current = None
    for cat, name, url in entries:
        if cat != current:
            lines.append(f"# {cat},#genre#")
            current = cat
        lines.append(f"{name},{url}")
    return "\n".join(lines) + "\n"


def build_m3u(entries, logo_map=None, updated=None):
    """生成 M3U 订阅文件。"""
    logo_map = logo_map or {}
    lines = ["#EXTM3U"]
    if updated:
        lines.append(f"# Generated by china-iptv-sources, updated at {updated}")
    for cat, name, url in entries:
        attrs = f'group-title="{cat}"'
        logo = logo_map.get(name)
        if logo:
            attrs += f' tvg-logo="{logo}"'
        lines.append(f"#EXTINF:-1 {attrs},{name}")
        lines.append(url)
    return "\n".join(lines) + "\n"


def write_outputs(entries, output_dir, logo_map=None, updated=None, stats=None):
    """写入 live.txt / live.m3u / stats.json，返回 (txt, m3u)。"""
    os.makedirs(output_dir, exist_ok=True)
    txt = build_txt(entries)
    m3u = build_m3u(entries, logo_map=logo_map, updated=updated)

    with open(os.path.join(output_dir, "live.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(txt)
    with open(os.path.join(output_dir, "live.m3u"), "w", encoding="utf-8", newline="\n") as f:
        f.write(m3u)
    if stats is not None:
        with open(os.path.join(output_dir, "stats.json"), "w", encoding="utf-8") as f:
            json.dump(stats, f, ensure_ascii=False, indent=2)
    return txt, m3u
